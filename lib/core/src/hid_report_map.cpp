#include "hid_report_map.h"

namespace jig {

namespace {

// Report ID 1, input: 3 buttons + 5 bits padding, int8 X, int8 Y, int8 wheel (4 bytes).
const uint8_t kMouse[] = {
    0x05, 0x01, 0x09, 0x02, 0xA1, 0x01, 0x85, 0x01, 0x09, 0x01, 0xA1, 0x00,
    0x05, 0x09, 0x19, 0x01, 0x29, 0x03, 0x15, 0x00, 0x25, 0x01, 0x95, 0x03,
    0x75, 0x01, 0x81, 0x02, 0x95, 0x01, 0x75, 0x05, 0x81, 0x03, 0x05, 0x01,
    0x09, 0x30, 0x09, 0x31, 0x09, 0x38, 0x15, 0x81, 0x25, 0x7F, 0x75, 0x08,
    0x95, 0x03, 0x81, 0x06, 0xC0, 0xC0,
};

// Report ID 2, input: 8 modifier bits, 1 reserved byte, 6 key usages 0x00..0x73 (reaches F24).
const uint8_t kKeyboard[] = {
    0x05, 0x01, 0x09, 0x06, 0xA1, 0x01, 0x85, 0x02,
    0x05, 0x07, 0x19, 0xE0, 0x29, 0xE7, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x08, 0x81, 0x02,
    0x95, 0x01, 0x75, 0x08, 0x81, 0x01,
    0x95, 0x06, 0x75, 0x08, 0x15, 0x00, 0x25, 0x73, 0x05, 0x07, 0x19, 0x00, 0x29, 0x73, 0x81, 0x00,
    0xC0,
};

}  // namespace

std::vector<uint8_t> buildReportMap(bool mouse, bool keyboard) {
  std::vector<uint8_t> map;
  if (mouse) map.insert(map.end(), kMouse, kMouse + sizeof(kMouse));
  if (keyboard) map.insert(map.end(), kKeyboard, kKeyboard + sizeof(kKeyboard));
  return map;
}

}  // namespace jig
